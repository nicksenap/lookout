import type { Attention } from "../src/core/types.ts";

/**
 * Rule-ranking cases. The test commits every `before`, writes every `after`, and
 * parses the real `git diff` output, so each case is a genuine git hunk.
 */
export interface RuleCase {
  name: string;
  path: string;
  before: string;
  after: string;
  attention: Attention;
  /** Labels that must be present. */
  labels?: string[];
  /** Labels that must be absent. */
  notLabels?: string[];
}

const pad = (lines: string[]) => lines.join("\n") + "\n";
const filler = (prefix: string, n: number) => Array.from({ length: n }, (_, k) => `${prefix}${k}`);

